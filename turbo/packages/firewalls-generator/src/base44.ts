/**
 * Generate Base44 firewall config.
 *
 * Data source: https://app.base44.com/.well-known/oauth-authorization-server
 *
 * Base44 exposes its workspace/app API through a single endpoint protected by
 * OAuth access tokens. The OAuth connector maps BASE44_TOKEN to the stored
 * BASE44_ACCESS_TOKEN secret, so runner traffic can use the normalized env key.
 */

import { writeOutput } from "./codegen";

const METADATA_URL =
  "https://app.base44.com/.well-known/oauth-authorization-server";
const PLACEHOLDER_VALUE = "base44_placeholder_token";

function generateTypeScript(): string {
  const lines: string[] = [
    "// Auto-generated from Base44 OAuth metadata.",
    `// Source: ${METADATA_URL}`,
    "// Regenerate: cd turbo && pnpm -F @vm0/firewalls-generator generate:base44",
    "//",
    "// DO NOT EDIT THIS FILE MANUALLY.",
    "",
    'import type { FirewallConfig } from "../firewall-types";',
    "",
    "export const base44Firewall = {",
    '  name: "base44",',
    '  description: "Base44 API",',
    "  placeholders: {",
    `    BASE44_TOKEN: "${PLACEHOLDER_VALUE}",`,
    "  },",
    "  apis: [",
    "    {",
    '      base: "https://app.base44.com/mcp",',
    "      auth: {",
    "        headers: {",
    '          Authorization: "Bearer ${{ secrets.BASE44_TOKEN }}",',
    "        },",
    "      },",
    "      permissions: [],",
    "    },",
    "  ],",
    "} as const satisfies FirewallConfig;",
    "",
  ];
  return lines.join("\n");
}

export async function generate(): Promise<void> {
  console.error("Generating Base44 firewall config...");
  const ts = generateTypeScript();
  writeOutput("base44", ts, import.meta.dirname);
}
