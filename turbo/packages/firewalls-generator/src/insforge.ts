/**
 * Generate InsForge firewall config.
 *
 * Data source: https://docs.insforge.dev/
 *
 * InsForge provides backend infrastructure for agent-native apps. Each project
 * has its own backend host (e.g. `your-project.us-west.insforge.app`), which
 * the user supplies as the `INSFORGE_DOMAIN` variable. The admin API key is
 * sent via the `X-API-Key` header.
 */

import { writeOutput } from "./codegen";

const DOCS_URL = "https://docs.insforge.dev/";
// API key format: ik_ prefix followed by alphanumeric characters.
const PLACEHOLDER_VALUE = "ik_CoffeeSafeLocalCoffeeSafeLocalCof";

function generateTypeScript(): string {
  const lines: string[] = [
    "// Auto-generated from InsForge API docs.",
    `// Source: ${DOCS_URL}`,
    "// Regenerate: cd turbo && pnpm -F @vm0/firewalls-generator generate:insforge",
    "//",
    "// DO NOT EDIT THIS FILE MANUALLY.",
    "",
    'import type { FirewallConfig } from "../firewall-types";',
    "",
    "export const insforgeFirewall = {",
    '  name: "insforge",',
    '  description: "InsForge project backend (API key auth)",',
    "  placeholders: {",
    `    INSFORGE_API_KEY: "${PLACEHOLDER_VALUE}",`,
    "  },",
    "  apis: [",
    "    {",
    '      base: "https://${{ vars.INSFORGE_DOMAIN }}",',
    "      auth: {",
    "        headers: {",
    '          "X-API-Key": "${{ secrets.INSFORGE_API_KEY }}",',
    "        },",
    "      },",
    "      permissions: [],",
    "    },",
    "  ],",
    "} as const satisfies FirewallConfig;",
    "",
  ];

  return lines.join("\n");
}

export async function generate(): Promise<void> {
  console.error("Generating InsForge firewall config...");
  const ts = generateTypeScript();
  writeOutput("insforge", ts, import.meta.dirname);
}
