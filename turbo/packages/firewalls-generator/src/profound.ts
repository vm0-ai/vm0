/**
 * Profound API firewall config generator.
 *
 * Data sources:
 * - https://docs.tryprofound.com/rest-api/introduction
 * - https://docs.tryprofound.com/rest-api/authentication
 *
 * Profound uses API key authentication via the X-API-Key header.
 * API key format is not publicly documented; using generic placeholder.
 */

import { writeOutput } from "./codegen";

const DOCS_URL = "https://docs.tryprofound.com/rest-api/introduction";
const PLACEHOLDER_VALUE = "CoffeeSafeLocalCoffeeSafeLocalCoffeeSafeLocalCof";

function generateTypeScript(): string {
  const lines: string[] = [
    "// Auto-generated from Profound API docs.",
    `// Source: ${DOCS_URL}`,
    "// Regenerate: cd turbo && pnpm -F @vm0/firewalls-generator generate:profound",
    "//",
    "// DO NOT EDIT THIS FILE MANUALLY.",
    "",
    'import type { FirewallConfig } from "../firewall-types";',
    "",
    "export const profoundFirewall = {",
    '  name: "profound",',
    '  description: "Profound API",',
    "  placeholders: {",
    `    PROFOUND_API_KEY: "${PLACEHOLDER_VALUE}",`,
    "  },",
    "  apis: [",
    "    {",
    '      base: "https://api.tryprofound.com",',
    "      auth: {",
    "        headers: {",
    '          "X-API-Key": "${{ secrets.PROFOUND_API_KEY }}",',
    "        },",
    "      },",
    "      permissions: [],",
    "    },",
    "  ],",
    "} as const satisfies FirewallConfig;",
    "",
  ];
  return lines.join("\n");
}

export async function generate(): Promise<void> {
  console.error("Generating Profound firewall config...");
  const ts = generateTypeScript();
  writeOutput("profound", ts, import.meta.dirname);
}
