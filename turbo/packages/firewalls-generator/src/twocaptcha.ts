/**
 * Generate 2Captcha firewall config.
 *
 * Data source: https://2captcha.com/api-docs
 *
 * 2Captcha authenticates by including the API key as the `clientKey`
 * field in the JSON request body. We declare a Bearer-header config so
 * the proxy still emits a matching firewall entry; the skill is
 * responsible for adding `clientKey` to the body.
 */

import { writeOutput } from "./codegen";

const DOCS_URL = "https://2captcha.com/api-docs";
// Format: 32 hex chars
const PLACEHOLDER_VALUE = "c0ffeesafelocal5afe10ca1c0ffeesa";

function generateTypeScript(): string {
  const lines: string[] = [
    "// Auto-generated from 2Captcha API docs.",
    `// Source: ${DOCS_URL}`,
    "// Regenerate: cd turbo && pnpm -F @vm0/firewalls-generator generate:twocaptcha",
    "//",
    "// DO NOT EDIT THIS FILE MANUALLY.",
    "",
    'import type { FirewallConfig } from "../firewall-types";',
    "",
    "export const twocaptchaFirewall = {",
    '  name: "twocaptcha",',
    '  description: "2Captcha API",',
    "  placeholders: {",
    `    TWOCAPTCHA_TOKEN: "${PLACEHOLDER_VALUE}",`,
    "  },",
    "  apis: [",
    "    {",
    '      base: "https://api.2captcha.com",',
    "      auth: {",
    "        headers: {",
    '          Authorization: "Bearer ${{ secrets.TWOCAPTCHA_TOKEN }}",',
    "        },",
    "      },",
    "      permissions: [],",
    "    },",
    "  ],",
    "} as const satisfies FirewallConfig;",
    "",
  ];
  return lines.join("\n");
}

export async function generate(): Promise<void> {
  console.error("Generating 2Captcha firewall config...");
  const ts = generateTypeScript();
  writeOutput("twocaptcha", ts, import.meta.dirname);
}
