import { mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { MODEL_PROVIDER_FIREWALL_CONFIGS } from "@vm0/api-contracts/contracts/model-providers";

import {
  type PythonBuiltinFirewallCatalogFile,
  type PythonBuiltinFirewallSourceFirewall,
  renderComposedPythonBuiltinFirewallCatalogFiles,
} from "./python-builtin-firewall-catalog-composition";

const generatedBuiltinFirewallCatalogPackagePath = fileURLToPath(
  new URL(
    "../../../../crates/runner/mitm-addon/src/generated/builtin_firewalls",
    import.meta.url,
  ),
);
const legacyGeneratedBuiltinFirewallCatalogPath = fileURLToPath(
  new URL(
    "../../../../crates/runner/mitm-addon/src/generated/builtin_firewalls.py",
    import.meta.url,
  ),
);

const pythonGeneratedHeader = [
  "# @generated by @vm0/firewalls-generator.",
  "# Do not edit by hand.",
  "# Regenerate with: cd turbo && pnpm -F @vm0/firewalls-generator generate",
  "# ruff: noqa",
] as const;

interface RenderProjectPythonBuiltinFirewallCatalogOptions {
  readonly maxJsonChunkLength?: number;
}

interface GeneratePythonBuiltinFirewallCatalogPackageOptions extends RenderProjectPythonBuiltinFirewallCatalogOptions {
  readonly outputPath?: string;
  readonly legacyOutputPath?: string;
}

function modelProviderFirewalls(): readonly PythonBuiltinFirewallSourceFirewall[] {
  return Object.values(MODEL_PROVIDER_FIREWALL_CONFIGS);
}

export async function renderProjectPythonBuiltinFirewallCatalogFiles({
  maxJsonChunkLength,
}: RenderProjectPythonBuiltinFirewallCatalogOptions = {}): Promise<
  readonly PythonBuiltinFirewallCatalogFile[]
> {
  return await renderComposedPythonBuiltinFirewallCatalogFiles({
    modelProviderFirewalls: modelProviderFirewalls(),
    generatedHeader: pythonGeneratedHeader,
    maxJsonChunkLength,
  });
}

export async function generatePythonBuiltinFirewallCatalogPackage({
  outputPath = generatedBuiltinFirewallCatalogPackagePath,
  legacyOutputPath = legacyGeneratedBuiltinFirewallCatalogPath,
  maxJsonChunkLength,
}: GeneratePythonBuiltinFirewallCatalogPackageOptions = {}): Promise<void> {
  await rm(outputPath, { recursive: true, force: true });
  await rm(legacyOutputPath, { force: true });
  await mkdir(outputPath, { recursive: true });

  for (const file of await renderProjectPythonBuiltinFirewallCatalogFiles({
    maxJsonChunkLength,
  })) {
    const filePath = join(outputPath, file.path);
    await mkdir(dirname(filePath), { recursive: true });
    await writeFile(filePath, file.content);
  }
}
