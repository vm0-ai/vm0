/**
 * Generate Pexels firewall config.
 *
 * Data source: https://www.pexels.com/api/documentation/
 *
 * Pexels authenticates API requests with an API key in the Authorization
 * header. Media asset URLs returned by the API live on separate CDN hosts and
 * do not require credentials.
 */

import {
  renderDefaultAllowed,
  renderDefaultUnknownPolicy,
  writeOutput,
} from "./codegen";

const DOCS_URL = "https://www.pexels.com/api/documentation/";
const PLACEHOLDER_VALUE = "CoffeeSafeLocalCoffeeSafeLocalCoffeeSafeLocal";
const DEFAULT_ALLOWED: string[] = [
  "photos.read",
  "collections.read",
  "videos.read",
  "media.download",
];

function generateTypeScript(): string {
  const lines: string[] = [
    "// Auto-generated from Pexels API docs.",
    `// Source: ${DOCS_URL}`,
    "// Regenerate: cd turbo && pnpm -F @vm0/firewalls-generator generate:pexels",
    "//",
    "// DO NOT EDIT THIS FILE MANUALLY.",
    "",
    'import type { FirewallConfig, FirewallPolicyValue, PermissionNamesOf } from "../firewall-types";',
    "",
    "export const pexelsFirewall = {",
    '  name: "pexels",',
    '  description: "Pexels API",',
    "  placeholders: {",
    `    PEXELS_API_KEY: "${PLACEHOLDER_VALUE}",`,
    "  },",
    "  apis: [",
    "    {",
    '      base: "https://api.pexels.com/v1",',
    "      auth: {",
    "        headers: {",
    '          Authorization: "${{ secrets.PEXELS_API_KEY }}",',
    "        },",
    "      },",
    "      permissions: [",
    "        {",
    '          name: "photos.read",',
    '          description: "Search and read Pexels photo metadata.",',
    "          rules: [",
    '            "GET /search",',
    '            "GET /curated",',
    '            "GET /photos/{id}",',
    "          ],",
    "        },",
    "        {",
    '          name: "collections.read",',
    '          description: "List and read Pexels collections.",',
    "          rules: [",
    '            "GET /collections",',
    '            "GET /collections/featured",',
    '            "GET /collections/{id}",',
    "          ],",
    "        },",
    "      ],",
    "    },",
    "    {",
    '      base: "https://api.pexels.com/videos",',
    "      auth: {",
    "        headers: {",
    '          Authorization: "${{ secrets.PEXELS_API_KEY }}",',
    "        },",
    "      },",
    "      permissions: [",
    "        {",
    '          name: "videos.read",',
    '          description: "Search and read Pexels video metadata.",',
    "          rules: [",
    '            "GET /search",',
    '            "GET /popular",',
    '            "GET /videos/{id}",',
    "          ],",
    "        },",
    "      ],",
    "    },",
    "    {",
    '      base: "https://images.pexels.com",',
    "      auth: {},",
    "      permissions: [",
    "        {",
    '          name: "media.download",',
    '          description: "Download or embed Pexels image assets returned by the API.",',
    '          rules: ["GET /{path+}"],',
    "        },",
    "      ],",
    "    },",
    "    {",
    '      base: "https://videos.pexels.com",',
    "      auth: {},",
    "      permissions: [",
    "        {",
    '          name: "media.download",',
    '          description: "Download or embed Pexels video assets returned by the API.",',
    '          rules: ["GET /{path+}"],',
    "        },",
    "      ],",
    "    },",
    "  ],",
    "} as const satisfies FirewallConfig;",
    "",
    ...renderDefaultAllowed(
      "pexelsDefaultAllowed",
      "pexelsFirewall",
      DEFAULT_ALLOWED,
    ),
    ...renderDefaultUnknownPolicy("pexelsDefaultUnknownPolicy", "deny"),
  ];
  return lines.join("\n");
}

export async function generate(): Promise<void> {
  console.error("Generating Pexels firewall config...");
  const ts = generateTypeScript();
  writeOutput("pexels", ts);
}
