import type { Firewall, FirewallApi } from "@vm0/connectors/firewall-types";
import { getAllConnectorFirewalls } from "@vm0/connectors/firewalls";
import { MODEL_PROVIDER_FIREWALL_CONFIGS } from "../contracts/model-providers";

type JsonValue =
  | string
  | number
  | boolean
  | null
  | readonly JsonValue[]
  | { readonly [key: string]: JsonValue };

export interface BuiltinFirewallCatalog {
  readonly firewalls: Record<string, Firewall>;
}

export interface PythonBuiltinFirewallCatalogFile {
  readonly path: string;
  readonly content: string;
}

interface RenderPythonBuiltinFirewallCatalogOptions {
  readonly catalog?: BuiltinFirewallCatalog;
  readonly maxJsonChunkLength?: number;
}

const DEFAULT_FIREWALL_JSON_CHUNK_LENGTH = 200_000;
const pythonGeneratedHeader = [
  "# @generated by @vm0/api-contracts.",
  "# Do not edit by hand.",
  "# Regenerate with: cd turbo && pnpm -F @vm0/api-contracts generate:rust",
  "# ruff: noqa",
] as const;

function runtimeApi(api: FirewallApi): FirewallApi {
  return {
    base: api.base,
    auth: api.auth,
    ...(api.permissions !== undefined ? { permissions: api.permissions } : {}),
  };
}

function runtimeFirewall(firewall: Firewall): Firewall {
  return {
    name: firewall.name,
    apis: firewall.apis.map(runtimeApi),
  };
}

export function buildBuiltinFirewallCatalog(): BuiltinFirewallCatalog {
  const connectorFirewalls = Object.values(getAllConnectorFirewalls()).map(
    (firewall) => {
      return runtimeFirewall(firewall);
    },
  );
  const modelProviderFirewalls = Object.values(
    MODEL_PROVIDER_FIREWALL_CONFIGS,
  ).map((firewall) => {
    return runtimeFirewall(firewall);
  });

  const firewalls: Record<string, Firewall> = {};
  for (const firewall of [...connectorFirewalls, ...modelProviderFirewalls]) {
    if (firewall.name in firewalls) {
      throw new Error(
        `duplicate built-in firewall catalog name: ${firewall.name}`,
      );
    }
    firewalls[firewall.name] = firewall;
  }

  return {
    firewalls,
  };
}

function sortJson(value: unknown): JsonValue {
  if (
    value === null ||
    typeof value === "string" ||
    typeof value === "number" ||
    typeof value === "boolean"
  ) {
    return value;
  }
  if (Array.isArray(value)) {
    return value.map(sortJson);
  }
  if (typeof value !== "object") {
    throw new Error(`unsupported JSON catalog value: ${typeof value}`);
  }

  const sorted: Record<string, JsonValue> = {};
  for (const key of Object.keys(value).sort()) {
    const nested = (value as Record<string, unknown>)[key];
    if (nested !== undefined) {
      sorted[key] = sortJson(nested);
    }
  }
  return sorted;
}

function stableCompactJson(value: unknown): string {
  return JSON.stringify(sortJson(value));
}

function pythonEscapedStringLiteral(value: string): string {
  const literal = JSON.stringify(value);
  if (literal === undefined) {
    throw new Error("failed to encode Python string literal");
  }
  return literal;
}

function hasOddTrailingBackslashes(value: string): boolean {
  let count = 0;
  for (let index = value.length - 1; index >= 0; index -= 1) {
    if (value[index] !== "\\") {
      break;
    }
    count += 1;
  }
  return count % 2 === 1;
}

function pythonJsonChunkLiteral(value: string): string {
  if (!value.includes('"""') && !hasOddTrailingBackslashes(value)) {
    return `r"""${value}"""`;
  }
  return pythonEscapedStringLiteral(value);
}

function sanitizePythonModuleBase(name: string): string {
  const sanitized = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .replace(/_+/g, "_");
  if (sanitized.length === 0) {
    return "firewall";
  }
  if (/^[a-z_]/.test(sanitized)) {
    return sanitized;
  }
  return `firewall_${sanitized}`;
}

function uniqueModuleBaseNames(
  names: readonly string[],
): ReadonlyMap<string, string> {
  const used = new Set<string>();
  const bases = new Map<string, string>();

  for (const name of names) {
    const base = sanitizePythonModuleBase(name);
    let candidate = base;
    let suffix = 2;
    while (used.has(candidate)) {
      candidate = `${base}_${suffix}`;
      suffix += 1;
    }
    used.add(candidate);
    bases.set(name, candidate);
  }

  return bases;
}

function splitString(value: string, maxLength: number): readonly string[] {
  if (!Number.isInteger(maxLength) || maxLength < 1) {
    throw new Error(`invalid firewall JSON chunk length: ${maxLength}`);
  }

  const chunks: string[] = [];
  for (let offset = 0; offset < value.length; offset += maxLength) {
    chunks.push(value.slice(offset, offset + maxLength));
  }
  return chunks.length > 0 ? chunks : [""];
}

function renderPythonPackageInit(): string {
  return [
    ...pythonGeneratedHeader,
    "",
    "import json",
    "from collections.abc import Iterator, Mapping",
    "from typing import Any",
    "",
    "from .loader import load_json_parts",
    "from .manifest import FIREWALL_MODULES",
    "",
    "",
    "class _BuiltinFirewallCatalog(Mapping[str, dict[str, Any]]):",
    "    def __init__(self) -> None:",
    "        self._cache: dict[str, dict[str, Any]] = {}",
    "",
    "    def __getitem__(self, name: str) -> dict[str, Any]:",
    "        if name not in FIREWALL_MODULES:",
    "            raise KeyError(name)",
    "        if name not in self._cache:",
    "            self._cache[name] = self._load(name)",
    "        return self._cache[name]",
    "",
    "    def __iter__(self) -> Iterator[str]:",
    "        return iter(FIREWALL_MODULES)",
    "",
    "    def __len__(self) -> int:",
    "        return len(FIREWALL_MODULES)",
    "",
    "    def __contains__(self, name: object) -> bool:",
    "        return name in FIREWALL_MODULES",
    "",
    "    def _load(self, name: str) -> dict[str, Any]:",
    "        parts = load_json_parts(name)",
    '        value = json.loads("".join(parts))',
    "        if not isinstance(value, dict):",
    '            raise TypeError(f"builtin firewall {name} is not a JSON object")',
    "        return value",
    "",
    "",
    "BUILTIN_FIREWALLS = _BuiltinFirewallCatalog()",
    "",
  ].join("\n");
}

function renderPythonLoader(
  modulesByFirewall: ReadonlyMap<string, readonly string[]>,
): string {
  const lines = [
    ...pythonGeneratedHeader,
    "",
    "",
    "def load_json_parts(name: str) -> tuple[str, ...]:",
  ];

  for (const [name, modules] of modulesByFirewall) {
    lines.push(`    if name == ${pythonEscapedStringLiteral(name)}:`);
    for (const moduleName of modules) {
      lines.push(`        from . import ${moduleName}`);
    }
    lines.push("");
    const renderedParts = modules
      .map((moduleName) => {
        return `${moduleName}.JSON_PART`;
      })
      .join(", ");
    const tupleSuffix = modules.length === 1 ? "," : "";
    lines.push(`        return (${renderedParts}${tupleSuffix})`);
  }

  lines.push("    raise KeyError(name)", "");
  return lines.join("\n");
}

function renderPythonManifest(
  modulesByFirewall: ReadonlyMap<string, readonly string[]>,
): string {
  const lines = [...pythonGeneratedHeader, "", "FIREWALL_MODULES = {"];

  for (const [name, modules] of modulesByFirewall) {
    const renderedModules = modules
      .map((moduleName) => {
        return pythonEscapedStringLiteral(moduleName);
      })
      .join(", ");
    const tupleSuffix = modules.length === 1 ? "," : "";
    lines.push(
      `    ${pythonEscapedStringLiteral(name)}: (${renderedModules}${tupleSuffix}),`,
    );
  }

  lines.push("}", "");
  return lines.join("\n");
}

function renderPythonJsonPartModule(jsonPart: string): string {
  return [
    ...pythonGeneratedHeader,
    "",
    `JSON_PART = ${pythonJsonChunkLiteral(jsonPart)}`,
    "",
  ].join("\n");
}

export function renderPythonBuiltinFirewallCatalogFiles(
  options: RenderPythonBuiltinFirewallCatalogOptions = {},
): readonly PythonBuiltinFirewallCatalogFile[] {
  const catalog = options.catalog ?? buildBuiltinFirewallCatalog();
  const maxJsonChunkLength =
    options.maxJsonChunkLength ?? DEFAULT_FIREWALL_JSON_CHUNK_LENGTH;
  const names = Object.keys(catalog.firewalls).sort();
  const moduleBaseNames = uniqueModuleBaseNames(names);
  const modulesByFirewall = new Map<string, readonly string[]>();
  const partFiles: PythonBuiltinFirewallCatalogFile[] = [];

  for (const name of names) {
    const firewall = catalog.firewalls[name];
    if (firewall === undefined) {
      throw new Error(`missing built-in firewall catalog entry: ${name}`);
    }

    const baseName = moduleBaseNames.get(name);
    if (baseName === undefined) {
      throw new Error(`missing Python module name for firewall: ${name}`);
    }

    const chunks = splitString(stableCompactJson(firewall), maxJsonChunkLength);
    const moduleNames = chunks.map((_, index) => {
      return `${baseName}_${index}`;
    });
    modulesByFirewall.set(name, moduleNames);

    for (let index = 0; index < chunks.length; index += 1) {
      const moduleName = moduleNames[index];
      const chunk = chunks[index];
      if (moduleName === undefined || chunk === undefined) {
        throw new Error(`missing generated Python chunk for firewall: ${name}`);
      }
      partFiles.push({
        path: `${moduleName}.py`,
        content: renderPythonJsonPartModule(chunk),
      });
    }
  }

  return [
    {
      path: "__init__.py",
      content: renderPythonPackageInit(),
    },
    {
      path: "manifest.py",
      content: renderPythonManifest(modulesByFirewall),
    },
    {
      path: "loader.py",
      content: renderPythonLoader(modulesByFirewall),
    },
    ...partFiles,
  ];
}
